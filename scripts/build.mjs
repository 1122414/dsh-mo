import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
process.chdir(fileURLToPath(new URL('..', import.meta.url)));
rmSync('.build', { recursive: true, force: true });
const command = process.platform === 'win32' ? 'tsc.cmd' : 'tsc';
const built = spawnSync(command, ['-p', 'tsconfig.json'], { stdio: 'inherit', shell: process.platform === 'win32' });
if (built.error || built.status !== 0) { console.error(built.error?.message ?? 'TypeScript build failed'); process.exit(1); }
writeFileSync('.build/package.json', '{"type":"commonjs"}\n');
// Closed, build-time-resolved local module table: no eval, new Function, or remote imports.
const factories = readdirSync('.build').filter(f => f.endsWith('.js')).sort().map(file =>
  `${JSON.stringify(file)}:function(module,exports,require){\n${readFileSync(resolve('.build', file), 'utf8')}\n}`);
const bundle = `/* Generated by npm run build; edit src/, not this file. */
window.__ModuleLoader__.load({id:"dsh-mo",factory(){
const modules={${factories.join(',\n')}};
const cache=Object.create(null);
function require(id){id=id.replace(/^\\.\\//,"");if(cache[id])return cache[id].exports;
if(!Object.hasOwn(modules,id))throw new Error("Unknown local module: "+id);
const module={exports:{}};cache[id]=module;modules[id](module,module.exports,require);return module.exports;}
return require("plugin.js");
}});
`;
mkdirSync('lib', { recursive: true });
writeFileSync('lib/client.js', bundle);
writeFileSync('lib/index.js', '// Host placeholder: no tools, routes, filesystem access, or model calls.\nexport const name = "dsh-mo";\nexport function apply() {}\n');
console.log(`Built lib/client.js (${Buffer.byteLength(bundle)} bytes); zero runtime dependencies.`);
